#!/usr/bin/env python3
"""Emit docs/generated/detectors.md from the code. Read-only against src/.

    python scripts/generate_detectors_doc.py            # write the file
    python scripts/generate_detectors_doc.py --check    # fail if the file is stale
    python scripts/generate_detectors_doc.py --stdout   # print, write nothing

Two sources, deliberately combined:

  runtime  imports network_behaviour for enum members, version identifiers and policy defaults
  static   parses src/network_behaviour/detectors/*.py to attribute evidence groups, reason codes
           and metric codes to the detector that actually emits them

The static half is the point. A hand-written contract claimed a Jensen-Shannon composition
detector and a synchronized-emergence suppressor; neither existed in src/, and the gap survived a
full acceptance suite. Deriving "what is emitted" from the syntax tree rather than from prose is
what makes that class of drift impossible to reintroduce.

Attribution walks the call graph within the detectors package, so evidence emitted through a
helper is credited to the detector that reaches the helper. It is static analysis: it reports what
the code can emit on some path, not what it emitted on a given day. Where that distinction matters
the output says so.
"""

from __future__ import annotations

import argparse
import ast
import pathlib
import sys
from collections import defaultdict

ROOT = pathlib.Path(__file__).resolve().parent.parent
DETECTOR_DIR = ROOT / "src" / "network_behaviour" / "detectors"
OUTPUT = ROOT / "docs" / "generated" / "detectors.md"
BANNER = "<!-- GENERATED by scripts/generate_detectors_doc.py — do not edit by hand -->"


# --------------------------------------------------------------------------- static analysis


class ModuleIndex:
    """Function bodies, call edges, and enum references across the detectors package."""

    def __init__(self, paths: list[pathlib.Path]) -> None:
        self.functions: dict[str, ast.FunctionDef] = {}
        self.calls: dict[str, set[str]] = defaultdict(set)
        self.family_of: dict[str, str] = {}
        for path in paths:
            tree = ast.parse(path.read_text(), filename=str(path))
            for node in ast.walk(tree):
                if not isinstance(node, ast.FunctionDef):
                    continue
                # Method and module-level function names collide rarely here; qualify by module.
                key = f"{path.stem}.{node.name}"
                self.functions[key] = node
                for call in _called_names(node):
                    self.calls[key].add(f"{path.stem}.{call}")
                    # helpers are often module-level in a sibling module
                    for other in paths:
                        self.calls[key].add(f"{other.stem}.{call}")
                family = _family_assigned_in(node)
                if family:
                    self.family_of[key] = family

    def reachable(self, start: str, depth: int = 4) -> set[str]:
        seen, frontier = {start}, {start}
        for _ in range(depth):
            nxt: set[str] = set()
            for key in frontier:
                for target in self.calls.get(key, ()):
                    if target in self.functions and target not in seen:
                        seen.add(target)
                        nxt.add(target)
            if not nxt:
                break
            frontier = nxt
        return seen

    def enum_refs(self, keys: set[str], enum_name: str) -> set[str]:
        found: set[str] = set()
        for key in keys:
            for node in ast.walk(self.functions[key]):
                if (
                    isinstance(node, ast.Attribute)
                    and isinstance(node.value, ast.Name)
                    and node.value.id == enum_name
                ):
                    found.add(node.attr)
        return found

    def metric_codes(self, keys: set[str]) -> set[str]:
        """Literal metric names: 2nd positional arg of DetectorEvidence, and _best_metric tuples."""
        found: set[str] = set()
        for key in keys:
            for node in ast.walk(self.functions[key]):
                if not isinstance(node, ast.Call):
                    continue
                name = _call_name(node)
                if name == "DetectorEvidence" and len(node.args) >= 2:
                    if isinstance(node.args[1], ast.Constant) and isinstance(
                        node.args[1].value, str
                    ):
                        found.add(node.args[1].value)
                elif name == "_best_metric":
                    for arg in node.args:
                        found.update(_string_literals(arg))
        return found


def _called_names(node: ast.AST) -> set[str]:
    names: set[str] = set()
    for child in ast.walk(node):
        if isinstance(child, ast.Call):
            called = _call_name(child)
            if called:
                names.add(called)
    return names


def _call_name(node: ast.Call) -> str | None:
    if isinstance(node.func, ast.Name):
        return node.func.id
    if isinstance(node.func, ast.Attribute):
        return node.func.attr
    return None


def _family_assigned_in(node: ast.FunctionDef) -> str | None:
    for child in ast.walk(node):
        if (
            isinstance(child, ast.Assign)
            and isinstance(child.value, ast.Attribute)
            and isinstance(child.value.value, ast.Name)
            and child.value.value.id == "DetectorFamily"
        ):
            return child.value.attr
    return None


def enum_reference_sites(root: pathlib.Path, enum_name: str, member: str) -> list[str]:
    """Modules under root referencing Enum.member, excluding the module that defines the enum."""
    sites: list[str] = []
    for path in sorted(root.rglob("*.py")):
        if path.name == "domain.py":
            continue
        try:
            tree = ast.parse(path.read_text(), filename=str(path))
        except SyntaxError:
            continue
        for node in ast.walk(tree):
            if (
                isinstance(node, ast.Attribute)
                and node.attr == member
                and isinstance(node.value, ast.Name)
                and node.value.id == enum_name
            ):
                sites.append(str(path.relative_to(root.parent)))
                break
    return sites


def _string_literals(node: ast.AST) -> set[str]:
    return {
        child.value
        for child in ast.walk(node)
        if isinstance(child, ast.Constant) and isinstance(child.value, str)
    }


# --------------------------------------------------------------------------- rendering


def build() -> str:
    sys.path.insert(0, str(ROOT / "src"))
    from network_behaviour.detectors.dns import (
        _DNS_METRIC_NAMES,
        _RATIO_METRICS,
    )
    from network_behaviour.detectors.dns import (
        DNS_SHARED_CONTEXT_METRICS as _SHARED_CONTEXT_METRICS,
    )
    from network_behaviour.detectors.engine import _LABELS
    from network_behaviour.detectors.models import (
        DETECTOR_VERSION,
        FAMILY_ORDER,
        DetectorPolicy,
    )
    from network_behaviour.domain import (
        DOMAIN_CODE_VERSION,
        RETIRED_EVIDENCE_GROUP_CODES,
        EvidenceGroup,
    )
    from network_behaviour.ranking.engine import _INDEPENDENT_CORROBORATION_GROUPS
    from network_behaviour.ranking.models import ORDERING_VERSION, RankingPolicy

    retired_text = ", ".join(str(c) for c in sorted(RETIRED_EVIDENCE_GROUP_CODES))
    index = ModuleIndex(sorted(DETECTOR_DIR.glob("*.py")))
    policy = DetectorPolicy()

    # family -> reachable function set
    per_family: dict[str, set[str]] = {}
    for key, family in index.family_of.items():
        per_family.setdefault(family, set()).update(index.reachable(key))

    emitted_groups: dict[str, set[str]] = {
        fam: index.enum_refs(keys, "EvidenceGroup") for fam, keys in per_family.items()
    }
    emitted_reasons: dict[str, set[str]] = {
        fam: index.enum_refs(keys, "ReasonCode") for fam, keys in per_family.items()
    }
    emitted_metrics: dict[str, set[str]] = {
        fam: index.metric_codes(keys) for fam, keys in per_family.items()
    }
    # DNS metric names live in a module constant, not in a _best_metric call.
    emitted_metrics.setdefault("DNS", set()).update(_DNS_METRIC_NAMES)
    emitted_metrics["DNS"].add("new_resolver")

    out: list[str] = [
        BANNER,
        "",
        "# Detectors — as implemented",
        "",
        "Emitted from `src/`. Never hand-edited; `--check` fails the build if this file drifts.",
        "`PRODUCT_CONTRACT.md` does not describe detector behavior, and this file does not state",
        "policy — parameter values live in `config/parameters.toml`.",
        "",
        f"Detector version `{DETECTOR_VERSION}` · ordering `{ORDERING_VERSION}` "
        f"· codes `{DOMAIN_CODE_VERSION}`",
        "",
        "## Families",
        "",
        "| Order | Family | Approved label | Evidence groups emitted | Reason codes |",
        "|---|---|---|---|---|",
    ]

    for family in sorted(FAMILY_ORDER, key=lambda f: FAMILY_ORDER[f]):
        key = family.name
        groups = sorted(emitted_groups.get(key, set()))
        reasons = sorted(emitted_reasons.get(key, set()))
        out.append(
            f"| {FAMILY_ORDER[family]} | `{family.value}` | {_LABELS[family]} | "
            f"{_codes(groups)} | {_codes(reasons)} |"
        )

    out += ["", "## Metric codes emitted", "", "| Family | Metric codes |", "|---|---|"]
    for family in sorted(FAMILY_ORDER, key=lambda f: FAMILY_ORDER[f]):
        metrics = sorted(emitted_metrics.get(family.name, set()))
        out.append(f"| `{family.value}` | {_codes(metrics)} |")

    # ---- the anti-drift table
    out += [
        "",
        "## Evidence groups: declared against emitted",
        "",
        "Every member of `EvidenceGroup`, and whether any detector can emit it on some path.",
        "A declared-but-unemitted group is a defect: the contract or the ranking engine believes",
        "in evidence that no detector produces.",
        "",
        f"Codes {retired_text} are retired and must never be reused. The gaps below are"
        " deliberate:",
        "these codes are a wire format stored in published feeds and packed into",
        "`evidence_group_mask`, so renumbering a survivor would reinterpret every published day.",
        "",
        "| Code | Group | Emitted by | Status |",
        "|---|---|---|---|",
    ]
    unemitted: list[str] = []
    for group in EvidenceGroup:
        producers = sorted(
            family.value
            for family in FAMILY_ORDER
            if group.name in emitted_groups.get(family.name, set())
        )
        if producers:
            status = "ok"
        else:
            unemitted.append(group.name)
            sites = enum_reference_sites(ROOT / "src", "EvidenceGroup", group.name)
            status = (
                "**NEVER EMITTED** — declared only, no reference in `src/`"
                if not sites
                else "**NEVER EMITTED** — referenced in "
                + ", ".join(f"`{s}`" for s in sites)
                + " but never constructed"
            )
        out.append(
            f"| {int(group)} | `{group.name}` | "
            f"{', '.join(f'`{p}`' for p in producers) if producers else '—'} | {status} |"
        )

    corroboration = sorted(g.name for g in _INDEPENDENT_CORROBORATION_GROUPS)
    dead_corroboration = [g for g in corroboration if g in unemitted]

    out += [
        "",
        "## Independent corroboration",
        "",
        "The ranking engine promotes an episode a full tier when it carries evidence from any",
        "of these groups whose `metric_strength` reaches",
        f"`RankingPolicy.corroboration_strength` ({RankingPolicy().corroboration_strength}).",
        "A group listed here that no detector emits is a route to the top tier that does not",
        "exist. Evidence below the strength stays on the episode and promotes nothing.",
        "",
        "| Group | Emitted? |",
        "|---|---|",
    ]
    for name in corroboration:
        out.append(f"| `{name}` | {'no — **dead route**' if name in unemitted else 'yes'} |")

    if dead_corroboration:
        live = [g for g in corroboration if g not in unemitted]
        live_text = ", ".join(f"`{g}`" for g in live)
        out += [
            "",
            f"> **{len(dead_corroboration)} of {len(corroboration)} corroboration routes are "
            f"dead.** Only {live_text} can promote an episode, so the tier boundary rests "
            "entirely on it. See `docs/CASE_STUDY.md` §8 for how selective that route is.",
        ]

    out += [
        "",
        "## Policy defaults compiled into the detectors",
        "",
        "Authoritative values are `config/parameters.toml`. These are the dataclass defaults",
        "actually in force; a mismatch between the two columns means the registry is not wired up.",
        "",
        "| Field | Compiled default |",
        "|---|---|",
    ]
    for field in policy.__dataclass_fields__:
        value = getattr(policy, field)
        # A support definition states itself; its repr would put an enum dump in the table.
        rendered = value.describe() if hasattr(value, "describe") else value
        out.append(f"| `{field}` | `{rendered}` |")

    ratio_text = ", ".join(f"`{m}`" for m in sorted(_RATIO_METRICS))
    shared_text = ", ".join(f"`{m}`" for m in sorted(_SHARED_CONTEXT_METRICS))
    out += [
        "",
        "## Notes",
        "",
        "- `transfer` and `fanout` score only addresses the support definition admits",
        f"  (`{policy.support.describe()}`, `{policy.support.version}`), and their peer and",
        "  calibration pools hold only admitted client-days. An address carrying nothing but",
        "  unaddressed rows has no service, so nothing external to measure. `dns` is not gated:",
        "  the activity source has no DNS rows, and the DNS family scores its own population.",
        "- The DNS population is the clients that sent at least one query that day, and a",
        "  client's resolvers are the ones it queried. An address whose only DNS row is an",
        "  unsolicited response takes no part: not in novelty's denominator, not a peer, and never",
        "  a prior DNS day.",
        "- A client-day that queried at least `dns_server_min_resolvers`",
        f"  ({policy.dns_server_min_resolvers}) resolvers is a DNS server. It gets a DNS",
        "  diagnostic and no DNS episode, and is left out of the DNS population.",
        "- The run turns the DNS family off for a day when the DNS population moved beyond",
        "  `drift.dns_population_step_fraction` against the same UTC weekday",
        "  (`network_behaviour.drift.assess_dns_coverage`); every client then reports",
        "  `MISSING_OPTIONAL_CONTEXT` for DNS, and the day publishes.",
        f"- DNS ratio metrics ({ratio_text}) are gated by the",
        "  packet and session support thresholds on the client-day. `new_resolver` carries its",
        f"  own floor of `dns_new_resolver_min_sessions` ({policy.dns_new_resolver_min_sessions})",
        "  on each new resolver, and reports nothing at all for a client with no prior DNS day.",
        f"- DNS shared-context metrics ({shared_text}) are emitted as evidence but",
        "  cannot establish eligibility or set the family strength: they describe the resolver,",
        "  not the client behind it.",
        "- Attribution is static. It reports what a detector can emit on some path, not what any",
        "  given run emitted. Optional-context groups appear only when their source is available.",
        "- A group marked *declared only* exists in the `EvidenceGroup` enum and nowhere else.",
        "  It is dead weight in the code, and a false promise wherever a document describes it.",
        "",
    ]
    return "\n".join(out)


def _codes(values: list[str]) -> str:
    return ", ".join(f"`{v}`" for v in values) if values else "—"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the file is stale")
    parser.add_argument("--stdout", action="store_true", help="print, write nothing")
    args = parser.parse_args()

    content = build()

    if args.stdout:
        print(content)
        return 0
    if args.check:
        current = OUTPUT.read_text() if OUTPUT.is_file() else ""
        if current != content:
            print(
                f"{OUTPUT} is stale. Run: python scripts/generate_detectors_doc.py", file=sys.stderr
            )
            return 1
        print(f"{OUTPUT} is current")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content)
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(content.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
