#!/usr/bin/env python3
"""Emit docs/generated/ordering.md from the code. Read-only against src/.

    python scripts/generate_ordering_doc.py            # write the file
    python scripts/generate_ordering_doc.py --check    # fail if the file is stale
    python scripts/generate_ordering_doc.py --stdout   # print, write nothing

`_tier()` was once described in no generated file, which is a Rule 1 violation hiding in plain
sight: episode tiering is the single most consequential decision after eligibility, and the only
account of it was the code.

Two sources, as in `generate_detectors_doc.py`:

  runtime  imports network_behaviour for enum members, version identifiers and policy defaults
  static   walks the `if` ladders in ranking/engine.py so the branch order and its conditions are
           transcribed from the syntax tree rather than paraphrased

The static half matters most for the ladder. A prose summary of an ordered `if` chain is exactly
the artifact that drifts: reorder two branches and the prose still reads true.
"""

from __future__ import annotations

import argparse
import ast
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ENGINE = ROOT / "src" / "network_behaviour" / "ranking" / "engine.py"
OUTPUT = ROOT / "docs" / "generated" / "ordering.md"
BANNER = "<!-- GENERATED by scripts/generate_ordering_doc.py — do not edit by hand -->"


def _function(tree: ast.Module, *path: str) -> ast.FunctionDef:
    """Find a module-level function, or a method of a class, by name."""
    scope: list[ast.stmt] = list(tree.body)
    node: ast.FunctionDef | None = None
    for name in path:
        found: ast.stmt | None = None
        for candidate in scope:
            if isinstance(candidate, ast.ClassDef | ast.FunctionDef) and candidate.name == name:
                found = candidate
                break
        if found is None:
            raise SystemExit(f"{'.'.join(path)} is absent from {ENGINE.name}")
        scope = list(found.body)
        node = found if isinstance(found, ast.FunctionDef) else None
    if node is None:
        raise SystemExit(f"{'.'.join(path)} is not a function")
    return node


def branch_ladder(function: ast.FunctionDef, source: str) -> list[tuple[str, str]]:
    """Every `if <condition>: return <value>` in evaluation order, plus the fall-through."""
    ladder: list[tuple[str, str]] = []
    for node in function.body:
        if isinstance(node, ast.If):
            returned = next(
                (item for item in node.body if isinstance(item, ast.Return)),
                None,
            )
            if returned is not None and returned.value is not None:
                ladder.append(
                    (
                        _segment(node.test, source),
                        _segment(returned.value, source),
                    )
                )
        elif isinstance(node, ast.Return) and node.value is not None:
            ladder.append(("otherwise", _segment(node.value, source)))
    return ladder


def assignments(function: ast.FunctionDef, source: str) -> dict[str, str]:
    """Named intermediates, so a ladder condition that reads `confidence_cap` is legible."""
    values: dict[str, str] = {}
    for node in function.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1:
            target = node.targets[0]
            if isinstance(target, ast.Name):
                values[target.id] = _segment(node.value, source)
    return values


def tuple_elements(function: ast.FunctionDef, source: str) -> list[str]:
    """The elements of a returned tuple, in order — the ordering key, term by term."""
    for node in ast.walk(function):
        if isinstance(node, ast.Return) and isinstance(node.value, ast.Tuple):
            return [_segment(element, source) for element in node.value.elts]
    raise SystemExit(f"{function.name} does not return a tuple")


def _segment(node: ast.AST, source: str) -> str:
    text = ast.get_source_segment(source, node) or ""
    return " ".join(text.split())


def build() -> str:
    sys.path.insert(0, str(ROOT / "src"))
    from network_behaviour.baselines.models import COMPATIBLE_BASELINE_VERSIONS
    from network_behaviour.detectors.models import DETECTOR_VERSION
    from network_behaviour.ranking.engine import _INDEPENDENT_CORROBORATION_GROUPS
    from network_behaviour.ranking.models import (
        COMPATIBLE_BEHAVIOUR_VERSION_PAIRS,
        ORDERING_VERSION,
        DataQualityConfidence,
        EvidenceTier,
        RankingPolicy,
    )

    source = ENGINE.read_text()
    tree = ast.parse(source, filename=str(ENGINE))
    tier = _function(tree, "RankingEngine", "_tier")
    policy = RankingPolicy()

    out: list[str] = [
        BANNER,
        "",
        "# Ordering and tiering — as implemented",
        "",
        "Emitted from `src/network_behaviour/ranking/engine.py`. Never hand-edited; `--check`",
        "fails the build if this file drifts. `PRODUCT_CONTRACT.md` does not describe ordering",
        "behavior, and parameter values live in `config/parameters.toml`.",
        "",
        f"Ordering `{ORDERING_VERSION}` · detectors `{DETECTOR_VERSION}`",
        "",
        "## Evidence tiers",
        "",
        "| Tier | Meaning |",
        "|---|---|",
        "| `E1` | Has corroborated strong evidence. **Not a priority** — it has held ~30% of the "
        "stream |",
        "| `E2` | Strong on one family, or moderate on two |",
        "| `E3` | Everything else that clears the moderate threshold, and everything capped by "
        "confidence |",
        "| `diagnostic` | Never enters the stream |",
        "",
        "## The tier ladder",
        "",
        "Branches in evaluation order, transcribed from the `if` chain in `_tier`. Order is the",
        "whole meaning: the first matching branch returns, so a later one only sees what earlier",
        "ones declined.",
        "",
        "| # | Condition | Tier |",
        "|---|---|---|",
    ]
    for index, (condition, value) in enumerate(branch_ladder(tier, source), start=1):
        out.append(f"| {index} | `{condition}` | `{value}` |")

    named = assignments(tier, source)
    if named:
        out += [
            "",
            "Named intermediates used by those conditions:",
            "",
            "| Name | Definition |",
            "|---|---|",
        ]
        for name, expression in named.items():
            out.append(f"| `{name}` | `{expression}` |")

    out += [
        "",
        "> A `confidence_cap` branch that precedes the E1 and E2 branches means no episode with",
        "> cold or limited history, limited data quality, or a low-confidence service can reach",
        "> E1 or E2, whatever its strength. That is a cap on evidence quality, not on strength,",
        "> and it is why tier and strength do not move together.",
        "",
        "## The ordering key",
        "",
        "`_rank_key`, term by term. Terms are compared in order; a negated term sorts descending.",
        "",
        "| # | Term |",
        "|---|---|",
    ]
    rank_key = _function(tree, "_rank_key")
    terms = tuple_elements(rank_key, source)
    for index, term in enumerate(terms, start=1):
        out.append(f"| {index} | `{term}` |")

    out += [
        "",
        f"`_tie_key` is `_rank_key` without the last term (`{terms[-1]}`), which is a digest and",
        "carries no evidence. Episodes equal on every remaining term share a `tie_group` and are",
        "**not ordered relative to each other**. The stream reports that rather than hiding it,",
        "because roughly 90% of adjacent within-tier pairs were tied on the original source",
        "(`CASE_STUDY` §12).",
        "",
        "## Independent corroboration",
        "",
        "Evidence groups that can promote an episode a full tier, and only when the evidence",
        f"carries a `metric_strength` of at least `{policy.corroboration_strength}`",
        "(`corroboration_strength`) — how unusual the large flow is against the ones the same",
        "host has already made. Presence alone promoted a tier until `episode-ordering-v4`;",
        "measured on 2026-08-09 that condition held for 26.01% of eligible relationship units",
        "and on 2026-08-11 for 80% of active addresses (`CASE_STUDY.md`, superseded values §8).",
        "",
    ]
    for group in sorted(item.name for item in _INDEPENDENT_CORROBORATION_GROUPS):
        out.append(f"- `{group}`")

    out += [
        "",
        "## Policy defaults compiled into the ranking engine",
        "",
        "Authoritative values are `config/parameters.toml`. These are the dataclass defaults",
        "actually in force; a mismatch between the two means the registry is not wired up.",
        "",
        "| Field | Compiled default |",
        "|---|---|",
    ]
    for field in RankingPolicy.__dataclass_fields__:
        out.append(f"| `{field}` | `{getattr(policy, field)}` |")

    out += [
        "",
        "## Compatible behaviour versions",
        "",
        "Reruns are forward-only: a published day is never re-derived, so these lists are what",
        "keeps already-published days readable. They are allow-lists, not conversion tables —",
        "no path exists between generations, and a day streams back in the generation it was",
        "built under. See `PRODUCT_CONTRACT.md` Tier 1, *Reruns: forward-only*.",
        "",
        "| Detector version | Ordering version |",
        "|---|---|",
    ]
    for detector, ordering in sorted(COMPATIBLE_BEHAVIOUR_VERSION_PAIRS):
        out.append(f"| `{detector}` | `{ordering}` |")

    out += [
        "",
        "Compatible baseline generations, checked separately because baselines set the",
        "denominators every strength is measured against:",
        "",
    ]
    for baseline in sorted(COMPATIBLE_BASELINE_VERSIONS):
        out.append(f"- `{baseline}`")
    out.append(
        "- a null `ops.pipeline_run.baseline_version` — published before migration `0009`"
        " recorded it"
    )

    quality = ", ".join(f"`{item.value}`" for item in DataQualityConfidence)
    tiers = ", ".join(f"`{item.value}`" for item in EvidenceTier)
    out += [
        "",
        "## Notes",
        "",
        f"- Tier vocabulary: {tiers}. Data-quality vocabulary: {quality}.",
        "- The ladder is transcribed from the syntax tree, so reordering two branches in the",
        "  engine changes this table. A prose summary would not have.",
        "- This file states what the engine does, not whether it should. Whether the ordering",
        "  carries information is measured, not asserted — see `docs/EVALUATION.md` §3.",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the file is stale")
    parser.add_argument("--stdout", action="store_true", help="print, write nothing")
    args = parser.parse_args()

    content = build()

    if args.stdout:
        print(content)
        return 0
    if args.check:
        current = OUTPUT.read_text() if OUTPUT.is_file() else ""
        if current != content:
            print(
                f"{OUTPUT} is stale. Run: python scripts/generate_ordering_doc.py",
                file=sys.stderr,
            )
            return 1
        print(f"{OUTPUT} is current")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content)
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(content.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
