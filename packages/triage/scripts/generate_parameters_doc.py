#!/usr/bin/env python3
"""Emit docs/generated/parameters.md from config/parameters.toml.

    python scripts/generate_parameters_doc.py            # write the file
    python scripts/generate_parameters_doc.py --check    # fail if the file is stale
    python scripts/generate_parameters_doc.py --stdout   # print, write nothing

The registry is the authority; this is its human-readable rendering. The point of rendering it is
the calibration-debt summary: how many parameters carry no record of what they were chosen to
achieve. That number is uncomfortable by design, and it should move in one direction.
"""

from __future__ import annotations

import argparse
import pathlib
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "config" / "parameters.toml"
OUTPUT = ROOT / "docs" / "generated" / "parameters.md"
BANNER = "<!-- GENERATED by scripts/generate_parameters_doc.py — do not edit by hand -->"

STATUS_ORDER = {"calibrated": 0, "provisional": 1, "inherited-unjustified": 2}
STATUS_LABEL = {
    "calibrated": "calibrated",
    "provisional": "provisional",
    "inherited-unjustified": "**unjustified**",
}


def _entries(data: dict[str, object]) -> list[tuple[str, dict[str, object]]]:
    """Flatten one level of tables into dotted names, keeping only parameter entries."""
    found: list[tuple[str, dict[str, object]]] = []
    for group, value in data.items():
        if not isinstance(value, dict):
            continue
        if "value" in value:
            found.append((group, value))
            continue
        for name, entry in value.items():
            if isinstance(entry, dict) and "value" in entry:
                found.append((f"{group}.{name}", entry))
    return sorted(found)


def _render_value(value: object) -> str:
    if isinstance(value, list):
        return "`" + ", ".join(str(v) for v in value) + "`"
    return f"`{value}`"


def build() -> str:
    data = tomllib.loads(REGISTRY.read_text())
    entries = _entries(data)

    counts: dict[str, int] = {}
    for _, entry in entries:
        status = str(entry.get("status", "unknown"))
        counts[status] = counts.get(status, 0) + 1
    total = len(entries)
    unjustified = counts.get("inherited-unjustified", 0)

    out: list[str] = [
        BANNER,
        "",
        "# Parameters — as configured",
        "",
        "Rendered from `config/parameters.toml`, which is the authority. Never hand-edited.",
        "Changing any value requires the evidence bundle in `docs/EVALUATION.md`.",
        "",
        "## Calibration debt",
        "",
        f"**{unjustified} of {total} parameters carry no record of what they were chosen"
        " to achieve.**",
        "",
        "| Status | Count | Meaning |",
        "|---|---:|---|",
        f"| calibrated | {counts.get('calibrated', 0)} | Fitted against a stated target,"
        " with the effect measured |",
        f"| provisional | {counts.get('provisional', 0)} | Proposed or not yet implemented;"
        " a target exists but is unmet |",
        f"| inherited-unjustified | {unjustified} | Arrived from contract v1."
        " No target on record |",
        "",
        "An unjustified parameter is not necessarily wrong. It is unexamined, which is a different",
        "problem and the one this table exists to keep visible.",
        "",
        "## Registry",
        "",
    ]

    by_status: dict[str, list[tuple[str, dict[str, object]]]] = {}
    for name, entry in entries:
        by_status.setdefault(str(entry.get("status", "unknown")), []).append((name, entry))

    for status in sorted(by_status, key=lambda s: STATUS_ORDER.get(s, 99)):
        out += [
            f"### {STATUS_LABEL.get(status, status)}",
            "",
            "| Parameter | Value | Fitted on | Target | Measured effect |",
            "|---|---|---|---|---|",
        ]
        for name, entry in by_status[status]:
            target = str(entry.get("target", "")) or "—"
            effect = str(entry.get("effect", "")) or "—"
            out.append(
                f"| `{name}` | {_render_value(entry['value'])} | "
                f"{entry.get('fitted_on', '—')} | {target} | {effect} |"
            )
        out.append("")

    out += [
        "## Reading this",
        "",
        "- **Fitted on** names the date and data range. `inherited` means it predates this",
        "  registry.",
        "- **Target** is what the value was chosen to achieve. Empty is the honest answer for",
        "  most of them and should not be filled in retrospectively with a guess.",
        "- **Measured effect** cites a `docs/CASE_STUDY.md` section rather than repeating a",
        "  number, so a stale measurement is visible at its source.",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the file is stale")
    parser.add_argument("--stdout", action="store_true", help="print, write nothing")
    args = parser.parse_args()

    content = build()

    if args.stdout:
        print(content)
        return 0
    if args.check:
        current = OUTPUT.read_text() if OUTPUT.is_file() else ""
        if current != content:
            print(
                f"{OUTPUT} is stale. Run: python scripts/generate_parameters_doc.py",
                file=sys.stderr,
            )
            return 1
        print(f"{OUTPUT} is current")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content)
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(content.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
